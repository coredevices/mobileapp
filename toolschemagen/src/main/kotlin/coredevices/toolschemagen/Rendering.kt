package coredevices.toolschemagen

internal const val DEFINITIONS_FILE = "BuiltinToolDefinitions"
internal const val CHECKPOINT_FILE = "LocalModelSchemaCheckpoint"

private const val GENERATED_HEADER = "// Generated by :toolschemagen; do not edit."

/** The `actual` live tool schemas, keyed by tool name. */
internal fun renderDefinitions(packageName: String, tools: List<ToolModel>): String = buildString {
    appendLine(GENERATED_HEADER)
    appendLine("package $packageName")
    appendLine()
    appendLine("import io.modelcontextprotocol.kotlin.sdk.types.Tool")
    appendLine("import io.modelcontextprotocol.kotlin.sdk.types.ToolSchema")
    appendLine("import kotlinx.serialization.json.JsonObject")
    appendLine("import kotlinx.serialization.json.JsonPrimitive")
    appendLine()
    appendLine("internal actual val builtinToolDefinitions: Map<String, Tool> = mapOf(")
    tools.forEach { tool ->
        appendLine("    ${tool.name.toKotlinLiteral()} to Tool(")
        appendLine("        name = ${tool.name.toKotlinLiteral()},")
        appendLine("        description = ${tool.description.toKotlinLiteral()},")
        appendSchema("inputSchema", tool.parameters)
        tool.outputParameters?.let { appendSchema("outputSchema", it) }
        appendLine("    ),")
    }
    appendLine(")")
}

private fun StringBuilder.appendSchema(argument: String, parameters: List<ToolParameterModel>) {
    appendLine("        $argument = ToolSchema(")
    appendLine("            properties = JsonObject(mapOf(")
    parameters.forEach { param ->
        appendLine("                ${param.name.toKotlinLiteral()} to JsonObject(mapOf(")
        appendLine("                    \"type\" to JsonPrimitive(${param.type.toKotlinLiteral()}),")
        param.description?.let {
            appendLine("                    \"description\" to JsonPrimitive(${it.toKotlinLiteral()}),")
        }
        appendLine("                )),")
    }
    appendLine("            )),")
    val required = parameters.filter { it.required }.joinToString { it.name.toKotlinLiteral() }
    appendLine("            required = listOf($required),")
    appendLine("        ),")
}

internal fun renderCheckpoint(packageName: String, checkpoint: Checkpoint): String = buildString {
    appendLine(GENERATED_HEADER)
    appendLine("package $packageName")
    appendLine()
    appendLine("import coredevices.toolschema.LocalModelSchemaCheckpoint")
    appendLine("import coredevices.toolschema.LocalModelTool")
    appendLine("import coredevices.toolschema.LocalModelToolParameter")
    appendLine()
    appendLine("internal actual val localModelSchemaCheckpoint = LocalModelSchemaCheckpoint(")
    appendLine("    modelVersion = ${checkpoint.modelVersion.toKotlinLiteral()},")
    appendLine("    excludedServlets = setOf(")
    checkpoint.excludedServlets.forEach { appendLine("        ${it.toKotlinLiteral()},") }
    appendLine("    ),")
    appendLine("    tools = listOf(")
    checkpoint.tools.forEach { tool ->
        appendLine("        LocalModelTool(")
        appendLine("            servlet = ${tool.servlet.toKotlinLiteral()},")
        appendLine("            name = ${tool.name.toKotlinLiteral()},")
        appendLine("            description = ${tool.description.toKotlinLiteral()},")
        appendLine("            parameters = listOf(")
        tool.parameters.forEach { param ->
            appendLine("                LocalModelToolParameter(")
            appendLine("                    name = ${param.name.toKotlinLiteral()},")
            appendLine("                    type = ${param.type.toKotlinLiteral()},")
            appendLine("                    description = ${param.description?.toKotlinLiteral()},")
            appendLine("                    required = ${param.required},")
            appendLine("                ),")
        }
        appendLine("            ),")
        appendLine("        ),")
    }
    appendLine("    ),")
    appendLine(")")
}

internal fun String.toSnakeCase(): String =
    replace(Regex("(?<=[a-z0-9])[A-Z]")) { "_" + it.value }.lowercase()

private fun String.toKotlinLiteral(): String = buildString {
    append('"')
    this@toKotlinLiteral.forEach { char ->
        when (char) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> append(char)
        }
    }
    append('"')
}
